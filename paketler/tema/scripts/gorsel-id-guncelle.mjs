let guncellenen = 0;
for (const u of katalog.urunler) {
  const yeni = idMap[u.id] ?? adIleGorsel(u.ad);
  if (u.gorselId !== yeni) {
    u.gorselId = yeni;
    guncellenen++;
  }
}

